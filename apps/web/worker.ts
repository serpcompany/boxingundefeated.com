/**
 * Worker entry (OpenNext's custom worker pattern). It hands each request to the pipeline in
 * lib/worker/handle-request.ts (build guard, canonical host, crawl policy, D1 readiness, edge
 * cache, then OpenNext), with the handler that `opennextjs-cloudflare build` generates as `serve`,
 * the environment `build:worker` recorded, the Cache API namespace the edge cache stores pages in,
 * and a per-isolate memo of D1's readiness.
 *
 * wrangler.jsonc `main` points here. tsconfig.json excludes this file because `.open-next/`
 * exists only after a Worker build; the pipeline it wires in is type-checked and unit-tested.
 */
// @ts-expect-error written by `build:worker` (scripts/write-build-environment.ts)
import buildEnvironment from './.open-next/build-environment.json'
// @ts-expect-error generated by `opennextjs-cloudflare build`
import openNextWorker from './.open-next/worker.js'
import { type DatasetReadinessMemo, d1DatasetReadiness } from './lib/worker/dataset-gate'
import { EDGE_CACHE_NAME } from './lib/worker/edge-cache'
import { handleWorkerRequest, type WorkerRequestEnvironment } from './lib/worker/handle-request'

// @ts-expect-error generated by `opennextjs-cloudflare build`
export { BucketCachePurge, DOQueueHandler, DOShardedTagCache } from './.open-next/worker.js'

let datasetReadiness: DatasetReadinessMemo | undefined

function log(event: object): void {
  console.info(JSON.stringify(event))
}

export default {
  fetch(
    request: Request,
    env: WorkerRequestEnvironment & { DB?: D1Database },
    ctx: ExecutionContext
  ): Promise<Response> {
    datasetReadiness ??= d1DatasetReadiness(env)
    const readiness = datasetReadiness
    return handleWorkerRequest(request, env, rendered => openNextWorker.fetch(rendered, env, ctx), {
      buildEnvironment,
      edgeCache: { context: ctx, openCache: () => caches.open(EDGE_CACHE_NAME) },
      datasetReadiness: () => readiness.current(),
      log
    })
  }
}

/**
 * Worker entry (OpenNext's custom worker pattern). For each request, in order:
 *
 * 1. Canonical host: with `CANONICAL_HOST_REDIRECT=on`, `www.boxingundefeated.com` and
 *    `*.workers.dev` get one 308 to the environment's origin, already in canonical slash form
 *    (lib/routing/canonical-host.ts). Requests with the smoke-test header are exempt.
 * 2. The environment's crawl policy (lib/worker/environment-policy.ts).
 * 3. The handler that `opennextjs-cloudflare build` generates. It applies the trailing-slash
 *    `redirects()` from next.config.ts (lib/routing/trailing-slash.ts) on the canonical host.
 *
 * wrangler.jsonc `main` points here. tsconfig.json excludes this file because `.open-next/`
 * exists only after a Worker build; the modules it wires in are type-checked and unit-tested.
 */
// @ts-expect-error generated by `opennextjs-cloudflare build`
import openNextWorker from './.open-next/worker.js'
import { type CanonicalHostEnvironment, canonicalHostRedirect } from './lib/routing/canonical-host'
import { type WorkerEnvironment, withEnvironmentPolicy } from './lib/worker/environment-policy'

// @ts-expect-error generated by `opennextjs-cloudflare build`
export { BucketCachePurge, DOQueueHandler, DOShardedTagCache } from './.open-next/worker.js'

export default {
  async fetch(
    request: Request,
    env: WorkerEnvironment & CanonicalHostEnvironment,
    ctx: ExecutionContext
  ): Promise<Response> {
    return (
      canonicalHostRedirect(request, env) ??
      withEnvironmentPolicy(request, env, () => openNextWorker.fetch(request, env, ctx))
    )
  }
}
